"""Offline, class-agnostic box-IoU HOTA and association accuracy.

Independent implementation of the sequence algorithm documented by TrackEval,
with an explicit unavailable result for wholly empty input. This is a local
box-IoU evaluation protocol, not a claim to run any official dataset benchmark.
Runtime modules and simulator ground truth are deliberately absent.
"""
from __future__ import annotations

from collections import Counter
import math

import numpy as np
from scipy.optimize import linear_sum_assignment

from .association_quality import _aliases, _box, _iou, _prepare


_ALPHAS = np.arange(.05, .99, .05)
_EPSILON = np.finfo(float).eps
_SCORES = ('hota', 'assa', 'deta', 'loca')
_REFERENCE_COMMIT = '12c8791b303e0a0b50f753af204249e622d0281a'
_REFERENCE_SHA256 = 'c582255c3d36bdb49c3ceeb2a5bd912cee009190dfcfe465b4173d03aaa97d6a'


def _protocol():
    return dict(
        name='class_agnostic_bbox_iou_hota_v1',
        reference_url=f'https://github.com/JonathonLuiten/TrackEval/blob/{_REFERENCE_COMMIT}/trackeval/metrics/hota.py',
        reference_commit=_REFERENCE_COMMIT, reference_sha256=_REFERENCE_SHA256,
        implementation='independent implementation of TrackEval sequence HOTA formulas; no upstream code vendored',
        scope='one annotated sequence; all supplied predictions and visible GT; labels and confidence do not choose matches; no class, ignore, crowd or benchmark preprocessing',
        similarity='half-open 2D bbox IoU in the common source image',
        matching='global soft-Jaccard track alignment times frame IoU, then one maximum-weight Hungarian assignment per frame before alpha filtering',
        alpha_thresholds=[float(alpha) for alpha in _ALPHAS],
        threshold_policy='IoU >= alpha - float64 epsilon; soft-potential denominator > float64 epsilon; alpha generated by numpy.arange(0.05, 0.99, 0.05)',
        float64_epsilon=float(_EPSILON),
        association='TP-weighted pair Jaccard using every GT/predicted trajectory observation, including unmatched observations',
        mean_policy='arithmetic mean of the 19 per-alpha scores; mean HOTA is not sqrt(mean DetA * mean AssA)',
        empty_match_loca='1 when TP=0, following TrackEval; this is a convention with no localization support',
        empty_sequence_policy='both GT and predictions empty => unavailable, deliberately differs from TrackEval zero-HOTA convention; one side empty => HOTA/AssA/DetA=0 and LocA=1',
        alias_policy='online unchanged; final aliases transitively resolved; cycles rejected; final IDs must remain unique within each frame or final scores are unavailable; observations never deduplicated',
        score_scale='fractions in [0, 1]')


def _support(frames, aliases):
    return dict(frames=len(frames),
        gt_observations=sum(len(frame['gt']) for frame in frames),
        predicted_observations=sum(len(frame['pred']) for frame in frames),
        unique_gt_ids=len({gt for frame in frames for gt in frame['gt']}),
        unique_predicted_ids=len({aliases.get(p['identity'], p['identity'])
            for frame in frames for p in frame['pred'] if p['identity'] is not None}))


def _unavailable(reason, support):
    return dict(available=False, reason=reason, support=support,
                protocol=_protocol(), mean=dict.fromkeys(_SCORES), per_alpha=[])


def _evaluate(frames, similarities, aliases, support):
    """Accumulate sparse trajectory pairs and solve only frame-sized matrices."""
    gt_counts, pred_counts, potential = Counter(), Counter(), Counter()
    identities = []
    for frame, similarity in zip(frames, similarities):
        gt_ids = frame['gt']
        pred_ids = [aliases.get(p['identity'], p['identity']) for p in frame['pred']]
        identities.append((gt_ids, pred_ids))
        gt_counts.update(gt_ids)
        pred_counts.update(pred_ids)
        denominators = similarity.sum(axis=1)[:, None] + similarity.sum(axis=0)[None, :] - similarity
        soft = np.divide(similarity, denominators, out=np.zeros_like(similarity),
                         where=denominators > _EPSILON)
        for row, col in zip(*np.nonzero(soft)):
            potential[gt_ids[row], pred_ids[col]] += float(soft[row, col])
    alignment = {pair: count/(gt_counts[pair[0]]+pred_counts[pair[1]]-count)
                 for pair, count in potential.items()}
    matched = [Counter() for _ in _ALPHAS]
    localization = [0.] * len(_ALPHAS)
    for (gt_ids, pred_ids), similarity in zip(identities, similarities):
        if not gt_ids or not pred_ids:
            continue
        weights = np.array([[alignment.get((gt, pred), 0.) for pred in pred_ids]
                            for gt in gt_ids]) * similarity
        rows, columns = linear_sum_assignment(-weights)
        for index, alpha in enumerate(_ALPHAS):
            for row, col in zip(rows, columns):
                if similarity[row, col] >= alpha - _EPSILON:
                    matched[index][gt_ids[row], pred_ids[col]] += 1
                    localization[index] += float(similarity[row, col])
    per_alpha = []
    for index, alpha in enumerate(_ALPHAS):
        pairs = matched[index]
        tp = sum(pairs.values())
        fn, fp = support['gt_observations']-tp, support['predicted_observations']-tp
        deta = tp/(tp+fn+fp)
        assa = math.fsum(count*count/(gt_counts[gt]+pred_counts[pred]-count)
                         for (gt, pred), count in pairs.items())/max(1, tp)
        loca = max(1e-10, localization[index])/max(1e-10, tp)
        per_alpha.append(dict(alpha=float(alpha), tp=tp, fp=fp, fn=fn,
            deta=deta, assa=assa, hota=math.sqrt(deta*assa), loca=loca))
    return dict(available=True, reason=None, support=support, protocol=_protocol(),
        mean={key: math.fsum(row[key] for row in per_alpha)/len(per_alpha)
              for key in _SCORES}, per_alpha=per_alpha)


def evaluate_tracking(frames, *, final_aliases=None) -> dict:
    """Evaluate historical online and optional final canonicalized identities.

    Input is the same normalized frame sequence as ``evaluate_association``:
    GT ``id`` persists, predicted observation ``id`` is globally unique, and
    predicted ``identity`` persists and is unique within each frame. Boxes are
    [x1,y1,x2,y2]; all observations require label, and predictions require score.
    A missing predicted identity makes both identity results unavailable. An
    explicitly empty alias mapping requests a final result with unchanged IDs.
    """
    aliases = _aliases(final_aliases)
    # Reuse the exact association input validation. Its local matches are not
    # used: HOTA requires its own globally aligned, threshold-independent match.
    prepared, missing, _ = _prepare(frames, .5)
    support = _support(prepared, {})
    final_support = _support(prepared, aliases or {})
    if missing:
        reason = 'missing predicted identity; detection-only observations cannot establish tracking'
        return dict(online=_unavailable(reason, support),
                    final_canonicalized=_unavailable(reason, final_support))
    if not support['gt_observations'] and not support['predicted_observations']:
        reason = 'no observation support: both GT and predicted sequences are empty'
        return dict(online=_unavailable(reason, support),
                    final_canonicalized=_unavailable(reason, final_support))
    similarities = [np.array([[_iou(_box(gt['bbox']), pred['bbox']) for pred in normalized['pred']]
                      for gt in frame['gt']], dtype=float).reshape(len(normalized['gt']), len(normalized['pred']))
                    for frame, normalized in zip(frames, prepared)]
    online = _evaluate(prepared, similarities, {}, support)
    if aliases is None:
        final = _unavailable('final aliases not supplied; online identities only', final_support)
    elif any(len({aliases.get(p['identity'], p['identity']) for p in frame['pred']}) != len(frame['pred'])
             for frame in prepared):
        final = _unavailable('final alias collision: identities are not unique within a frame; observations retained', final_support)
    else:
        final = _evaluate(prepared, similarities, aliases, final_support)
    return dict(online=online, final_canonicalized=final)
